// Lookup translation in local dictionary
function localDictLookup(text, sourceLang, targetLang) {
  if (!text) return null;
  const trimmed = text.trim();
  if (!trimmed) return null;

  // direct key lookup
  const key = `${sourceLang}|${targetLang}`;
  const dict = LOCAL_DICT[key];
  if (dict) {
    if (dict[trimmed]) return dict[trimmed];
    // case-insensitive for latin scripts
    const lower = trimmed.toLowerCase();
    if (dict[lower]) return dict[lower];
  }
  return null;
}

// Smart dialect translation with rule-based fallback
function dialectTranslate(text, sourceLang, targetLang) {
  if (!text) return { text: '', confidence: 0, isRuleBased: false };
  const trimmed = text.trim();
  if (!trimmed) return { text: '', confidence: 0, isRuleBased: false };

  // 1. Try direct dictionary lookup first
  const direct = localDictLookup(trimmed, sourceLang, targetLang);
  if (direct) {
    return { text: direct, confidence: 1, isRuleBased: false };
  }

  // 2. For dialect <-> zh-CN, apply rule-based partial mapping
  const isDialectToMandarin = DIALECT_CODES.includes(sourceLang) && targetLang === 'zh-CN';
  const isMandarinToDialect = sourceLang === 'zh-CN' && DIALECT_CODES.includes(targetLang);

  if ((isDialectToMandarin || isMandarinToDialect) && DIALECT_RULES[targetLang]) {
    const rules = DIALECT_RULES[targetLang].phrases;
    let result = trimmed;
    let appliedCount = 0;
    for (const rule of rules) {
      const before = result;
      result = result.replace(rule.from, rule.to);
      if (result !== before) appliedCount++;
    }
    if (appliedCount > 0) {
      const confidence = Math.min(0.95, 0.4 + appliedCount * 0.15);
      return { text: result, confidence, isRuleBased: true, appliedRules: appliedCount };
    }
  }

  // 3. For dialect -> other standard lang, first translate dialect->zh-CN then use API
  if (DIALECT_CODES.includes(sourceLang) && targetLang !== 'zh-CN') {
    const dialectToMandarin = dialectTranslate(trimmed, sourceLang, 'zh-CN');
    if (dialectToMandarin.confidence > 0) {
      return {
        text: dialectToMandarin.text,
        confidence: dialectToMandarin.confidence * 0.8,
        isRuleBased: true,
        note: '方言先转普通话，再使用在线翻译',
      };
    }
  }

  return { text: '', confidence: 0, isRuleBased: false };
}

// Generate alternative translation suggestions
function getAlternatives(text, sourceLang, targetLang) {
  const alts = [];
  if (!text) return alts;

  const key = `${sourceLang}|${targetLang}`;
  const dict = LOCAL_DICT[key];
  if (!dict) return alts;

  // Find entries that contain the text or are similar
  const trimmed = text.trim();
  for (const [k, v] of Object.entries(dict)) {
    if (k !== trimmed && (k.includes(trimmed) || trimmed.includes(k))) {
      alts.push({ source: k, target: v });
      if (alts.length >= 3) break;
    }
  }
  return alts;
}

